OPS = {"¬":"NOT", "~":"NOT", "!":"NOT", "∧":"AND", "&":"AND", "∨":"OR", "|":"OR", "→":"IMP", "->":"IMP", "=>":"IMP", "↔":"IFF", "<->":"IFF", "<=>":"IFF"}
TOKEN_RE = re.compile(r"<->|<=>|->|=>|[()¬~!∧&∨|→↔]|[A-Za-z][A-Za-z0-9_]*")
class LogicError(Exception): pass

def tokenize(formula):
    tokens = TOKEN_RE.findall(formula)
    if "".join(tokens).lower() != re.sub(r"\s+", "", formula).lower():
        raise LogicError("สูตรมีสัญลักษณ์ที่ไม่รองรับ กรุณาใช้ p, q, r และ ¬ ∧ ∨ → ↔ พร้อมวงเล็บ")
    out=[]
    for t in tokens:
        out.append(OPS.get(t,t))
    if not out: raise LogicError("กรุณาป้อนสูตรก่อน")
    return out

class Parser:
    def __init__(self,tokens): self.t=tokens; self.i=0
    def peek(self): return self.t[self.i] if self.i<len(self.t) else None
    def take(self):
        x=self.peek()
        if x is not None: self.i+=1
        return x
    def parse(self):
        n=self.iff()
        if self.peek() is not None: raise LogicError(f"พบสัญลักษณ์เกินหรือผิดตำแหน่ง: {self.peek()}")
        return n
    def iff(self):
        n=self.imp()
        while self.peek()=="IFF": self.take(); n=("IFF",n,self.imp())
        return n
    def imp(self):
        n=self.or_expr()
        if self.peek()=="IMP": self.take(); n=("IMP",n,self.imp())
        return n
    def or_expr(self):
        n=self.and_expr()
        while self.peek()=="OR": self.take(); n=("OR",n,self.and_expr())
        return n
    def and_expr(self):
        n=self.neg()
        while self.peek()=="AND": self.take(); n=("AND",n,self.neg())
        return n
    def neg(self):
        if self.peek()=="NOT": self.take(); return ("NOT",self.neg())
        return self.atom()
    def atom(self):
        t=self.take()
        if t is None: raise LogicError("สูตรไม่สมบูรณ์")
        if t=="(":
            n=self.iff()
            if self.take()!=")": raise LogicError("วงเล็บเปิดและปิดไม่ครบ")
            return n
        if t==")" or t in ("AND","OR","IMP","IFF","NOT"): raise LogicError("ตัวดำเนินการอยู่ผิดตำแหน่ง")
        return ("VAR",t)

def parse_formula(s): return Parser(tokenize(s)).parse()
def variables(n):
    if n[0]=="VAR": return {n[1]}
    if n[0]=="NOT": return variables(n[1])
    return variables(n[1])|variables(n[2])
def evaluate(n,v):
    k=n[0]
    if k=="VAR": return v[n[1]]
    if k=="NOT": return not evaluate(n[1],v)
    a,b=evaluate(n[1],v),evaluate(n[2],v)
    return {"AND":a and b,"OR":a or b,"IMP":(not a) or b,"IFF":a==b}[k]
def make_table(nodes):
    vs=sorted(set().union(*(variables(n) for n in nodes)))
    if len(vs)>8: raise LogicError("เครื่องมือนี้รองรับตัวแปรไม่เกิน 8 ตัว")
    rows=[]
    for combo in itertools.product([True,False],repeat=len(vs)):
        val=dict(zip(vs,combo)); row={x:("T" if val[x] else "F") for x in vs}
        for i,n in enumerate(nodes): row[f"สูตร {i+1}"]="T" if evaluate(n,val) else "F"
        rows.append(row)
    return vs,rows

