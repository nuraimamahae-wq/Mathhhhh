    _,rows=make_table([n]); vals=[r["สูตร 1"] for r in rows]
    if all(x=="T" for x in vals): return "สัจนิรันดร์ (Tautology)"
    if all(x=="F" for x in vals): return "ข้อขัดแย้ง (Contradiction)"
    return "ประพจน์ไม่แน่นอน (Contingency)"

